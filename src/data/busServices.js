/**
 * Returns "towards <Destination>" for a given bus service number,
 * or "In Service" if the service is unknown.
 */
export function getBusServiceTerminus(serviceNo) {
  const s = BUS_SERVICE_ROUTES[String(serviceNo).trim()];
  if (s && s.destination) return `towards ${s.destination}`;
  return 'In Service';
}

/**
 * Returns the origin terminus name for a given bus service number, or null.
 */
export function getBusServiceOrigin(serviceNo) {
  const s = BUS_SERVICE_ROUTES[String(serviceNo).trim()];
  return s?.origin || null;
}

/**
 * Returns the operator code for a given bus service number.
 * Defaults to 'SBST' if unknown.
 */
export function getBusServiceOperator(serviceNo) {
  const s = BUS_SERVICE_ROUTES[String(serviceNo).trim()];
  return s?.operator || 'SBST';
}
